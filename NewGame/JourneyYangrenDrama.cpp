#include "JourneyEpisode.hpp"
#include "StrategistJourney.hpp"

namespace frontline
{
    void BuildEpicCampaignDrama(const StrategistJourney& j,JourneyEpisode& e)
    {
        if(j.mission==YellowTurbanMission && j.stage==JourneyStage::Preparation && j.history[2].review.resolution==JourneyResolution::JoinedMainForce)
            e.lines.insert(e.lines.begin(),{
                {-1,U"黄巾の旗が、村から州郡へ広がっていた。義勇軍は道中の別働任務を本隊へ預け、皇甫嵩のもとへ向かう。",U"一八四年。野営の夜を重ね、小さな旗が官軍の陣へたどり着いた。"},
                {0,U"あの道で、お前が選んだことを覚えている。今度は、もっと多くの兵がお前の合図を待つ。軍師、一緒に行こう。",U"劉備が主人公の肩に手を置く。北と南の太鼓が鳴り始める。"}});
        if(!j.HasYangrenStrategy()) return;
        e.title=U"第二章　陽人・虎とともに";
        e.setting=U"森の向こうに呂布の騎兵。南道には孫堅の旗。合流した後にも、敵の反撃が待っている。";
        e.question=j.ObjectiveBrief();
        if(j.stage==JourneyStage::Preparation)
            e.lines={
                {LuBu,U"森へ隠れたくらいで、俺を止められると思うな。……親衛の騎兵は残せ。孫堅の旗が動いてからだ。",U"呂布は先鋒を送り、本陣の後ろにもう一列の騎兵を留める。"},
                {SunJian,U"俺は南道から出る。先に呂布を森で崩すなら待とう。一緒に押すなら、合流した後の反撃まで引き受けるぞ！",U"孫堅が山道の出口へ、自分の旗を立てる。"},
                {1,U"平地で馬と競う必要はない。林へ入らせ、隊列を崩す。孫堅殿を待たせる間は、南の道も守ろう。",U"関羽は森の入口へ駒を置く。"},
                {2,U"待つのは苦手だが、味方を置いていくのはもっと嫌いだ！ 軍師、俺が走る時を決めてくれ。",U"張飛が孫堅の旗と呂布の本陣を交互に見る。"},
                {0,U"合流できたら終わり、とは思わない方がよさそうだね。君の隣で、最後の騎兵が退くまで旗を守ろう。",U"劉備が主人公の旗を孫堅の旗のそばへ寄せる。"},
                {3,U"森で先鋒を崩すか、孫堅殿と一緒に押すか。出陣したら俺が決める。どちらでも、反撃の時に仲間を一人にしない。",U"主人公は南道へ伝令を出した。森の向こうから、馬の蹄が響く。"}};
        else if(j.won)
        {
            const auto& y=j.history[YangrenMission].review.grand.yangren;
            e.lines={
                {-1,U"親衛の騎兵が退く。孫堅の旗と義勇軍の旗が、同じ辻に残った。",U"敵を追う声が止み、隣にいる兵の名が呼ばれる。"},
                {SunJian,y.mainReturned>=3500 ? U"お前の合図で、俺の兵も帰ってこられた。軍師、次も隣で戦え。今度は都への道を決めよう。":
                    U"兵は失った。それでも、最後に俺の隣へ旗を立ててくれたな。戻らなかった者の名を聞いてから、次の道を考えよう。",U"孫堅が主人公へ手を伸ばす。"},
                {2,U"あの馬ども、やっと帰りやがった！ おい軍師、孫堅殿も戻ったぞ。今夜くらい、肩の力を抜けよ。",U"張飛が笑う。関羽は最後に戻る隊を待っている。"},
                {3,U"帰った隊から休ませてくれ。ここを守った兵が、次の道を歩く。今夜は、その顔を覚えておきたい。",U"主人公は二つ並んだ軍旗の間へ戻る。"}};
            if(j.stage==JourneyStage::Complete)
                e.lines.push_back({SunJian,j.SunJianTrust()>=SunJianFlankTrust ?
                    U"洛陽の南門を開くか、西で逃げる荷駄を捕らえるか。陽人でお前が見せた指揮なら、どちらも任せられる。一つ選べ。":
                    U"俺は洛陽へ向かう。南門の外で敵を引き受けてくれ。旗が見えたら、本隊を入れる。",U"焼けた都から報せが届く。孫堅が、新しい地図を差し出す。"});
        }
        else e.lines={
            {SunJian,U"合図の後にも、敵は来る。次は合流した場所で、誰を残すかまで決めよう。俺も、南からお前の旗を見る。",U"陽人からの撤収。二つの軍の伝令が、同じ地図へ印を置く。"},
            {3,U"合流を急いで、次の騎兵を見るのが遅れた。今度は皆が立てる場所を残す。戻った兵から、話を聞かせてくれ。",U"主人公は森と辻と南道を、一本の線でつなぎ直した。"}};
    }
}
