#include "JourneyEpisode.hpp"
namespace frontline
{
    JourneyEpisodeLine DefenseAftermathVoice(int actor,int other,int kind,bool painful)
    {
        const char32_t* normal[][3]={
            {U"火のそばに、私たちの兵がいた。軍師、そこに残す役も渡してくれたんだね。",U"烽火の守備が成った時、私もそこにいた。軍師、前へ出すだけが策ではあるまい。",U"俺の隊も火を支えたぞ！ 追いかけるだけじゃねえ。残る役だって、俺に任せていいんだぜ！"},
            {U"私の手も、使い切っていた。軍師、次は火を守る余力まで、一緒に考えよう。",U"手を使い、火の前で構えられぬ時があった。軍師、次の策には、残す手も入れてくれ。",U"手を使い切って、踏ん張れねえ時があった。軍師、次は誰を残す？ 俺も一緒に考えるぞ。"},
            {U"私も一手をつないだよ。軍師、誰か一人で片づけた戦いにはしないでおこう。",U"私も一手をつないだ。だが、その手だけで一戦は語れぬ。火の前に残った者の名も、地図に残そう。",U"つなぐ手なら、俺も出したぜ！ けど、残った奴の分まで、俺の手柄にするなよ？"}};
        const char32_t* painfulLines[][3]={
            {U"火を支えられた時もあった。でも軍師、今日の話を、そこだけで終わらせたくはないね。",U"守備を担った記録はある。だが軍師、帰ってきた兵と、果たせなかったことも同じ地図に置け。",U"俺の隊も火を支えた。……けどよ軍師、今日はそれだけで笑って済ませねえぞ。"},
            {U"手を使い切ったのは、私も同じだ。軍師、君一人を責めて、今日の話を終わらせはしないよ。",U"火の前で構えられなかったことも、私の記録だ。軍師、次は残す余力から話そう。",U"俺も手を使い切ってたんだ。軍師、失敗した手も消すなよ。俺たちで次を考えようぜ。"},
            {U"手はつながった。けれど、それだけでは届かなかったものも、一緒に持ち帰ろう。",U"連鎖は担った。だが軍師、つながった手だけを見て、今日の代償を隠すな。",U"俺もつないだぜ。でもよ、今日の話は、そこだけで終わりじゃねえだろ。"}};
        const char32_t* address[]={U"兄者",U"雲長",U"翼徳"};
        std::u32string text=(painful ? painfulLines:normal)[kind][actor];
        if(other>=0 && other<3)
        {
            text=std::u32string(address[other])+U"、"+text;
            if(actor==1 && other==0)
                text=std::u32string(U"兄者、")+(painful ?
                    kind==0 ? U"私も守備を担いました。ですが、今日の代償も同じ地図に残しましょう。軍師、その上で次を考えるぞ。":
                    kind==1 ? U"私にも構えられぬ時がありました。軍師、次は残す余力から話そう。":
                    U"私も連鎖を担いました。軍師、つながった手だけで今日を語るな。":
                    kind==0 ? U"私も火の守りを担いました。軍師、前へ出すだけが策ではあるまい。":
                    kind==1 ? U"私にも、火の前で構えられぬ時がありました。軍師、次の策には残す手も入れてくれ。":
                    U"私も一手をつなぎました。火の前に残った名も、同じ地図に残しましょう。");
        }
        return {actor,text,kind==1 ? U"使った手と残せなかった構えを、武将自身が地図に示す。":kind==0 ? U"武将は、守備が確認された烽火の印へ手を置く。":U"武将は、自分の駒だけを前へ押し出さずに話す。",painful || kind==1 ? 0:1<<actor};
    }
}
