#include "JourneyEpisode.hpp"
#include "JourneyCampaign.hpp"
#include "StrategistJourney.hpp"

namespace frontline
{
    JourneyEpisode BuildYellowTurbanEpisode(const StrategistJourney& j)
    {
        if(j.PlansGrandBattle() || j.HasGrandBattle()) return BuildGrandBattleEpisode(j);
        const auto beat=CampaignBeat(j);
        JourneyEpisode e;
        e.title=beat.phase;
        e.place=U"一八四年・黄巾の乱 ／ 広宗郊外";
        e.setting=beat.change;
        e.question=beat.next;
        if(j.stage==JourneyStage::Preparation)
            e.lines={
                {-1,U"一八四年。張角に従う人々は黄巾をしるしに各地で挙兵した。劉備は校尉・鄒靖に従い、義勇兵を率いて戦いに加わった。",
                    U"史実の戦いを背景に、義勇軍の別働隊の役目を描く。"},
                {ZhangJiao,U"お前に渡せるのは旗だけだ、梁。飢えたとき、誰が隣にいてくれたか。兵にはそれを思い出させてやれ。",
                    U"蜂起の頃。張角は弟の手に、黄いろい布を結んだ。"},
                {HuangfuSong,U"昼のうちに何度でも敵の目を引け。陣を捨てて出てくるまで待つ。功を急いで先に崩れるな。",
                    U"広宗。官軍を率いる皇甫嵩が別働隊への指図を出す。"},
                {ZhangLiang,U"兄者の旗は下ろさぬ。だが旗を守るのは木の柵じゃない。俺が前に立つ。南の隊は、呼ぶまで手を出すな。",
                    U"黄巾の前陣。張梁は、門を見張る兵の列に自ら入った。"},
                {0,U"鄒靖殿から、前陣を攻める役目を預かった。だが南の街道には、まだ家を出た人たちがいる。戦があそこまで来るとは思っていない。",
                    U"劉備は広宗の地図を広げ、街道の脇に残る集落を示す。"},
                {2,U"だったら先に旗を倒そうぜ。南の連中が街道へ出たら、あの陣は手薄になる。戻るまでに俺が取る。",
                    U"張飛が手を止め、南から前陣へ伸びる道を指でなぞる。"},
                {1,U"旗を取る隊と、人を逃がす隊か。翼徳、二つともやるなら、同じ道に三隊を並べる余裕はないぞ。",
                    U"関羽は林に駒を置く。もう一つの駒を、張飛へ渡した。"},
                {3,U"南の隊が動いたら俺が合図を出す。進めと言うか、街道へ行けと言うかは、皆の位置を見て決める。",
                    U"主人公が二つの道に指を置く。三人がうなずいた。"}};
        else if(j.stage==JourneyStage::Complete)
            e.lines={
                {-1,U"張角はすでに没していた。その年の冬、皇甫嵩は広宗で張梁の軍を破り、続いて下曲陽で張宝の軍を破った。",
                    U"一八四年・冬。各地の反乱はなお続くが、張角の一族が率いた大きな蜂起は崩れた。"},
                {0,U"鄒靖殿に従った働きで、安喜の尉を任されたよ。今度はあの町で、戦が終わったあとの人の暮らしを見てみたい。",
                    U"劉備が辞令を置く。畳まれた軍旗の脇に、初めて役所の印が並ぶ。"},
                {2,U"お役人かよ、兄者が！ ……まあ、村で話を聞くのは、いつもと変わらねえか。",
                    U"張飛は笑い、旅支度の袋を肩にかける。"},
                {3,U"行こう。いつかまた兵を動かすとき、地図の中で何を守るか、思い出せるように。",
                    U"主人公は広宗の地図を折った。第一章・完。"}};
        else if(j.won)
        {
            const auto& result=j.GuangzongSupport();
            e.lines={
                {-1,U"黄巾の前陣に義勇軍の旗が立った。官軍の隊列が、その脇を抜けて前へ出る。",U"広宗郊外。前陣の占領が確かめられる。"},
                {HuangfuSong,result.swift ? U"南翼が戻る前に旗を替えたか。よし、全軍前へ！ 鄒靖、あの軍師に兵を預けてやれ。次もあの目が役に立つ。":
                    U"この門から先は私の兵が行く。そなたの隊は負傷者を連れ帰れ。",
                    result.swift ? U"合図を見た官軍本隊が前陣を抜け、広宗へ向けて動き出す。":
                    U"皇甫嵩は前陣の守りを引き取った。"},
                {result.roadOfficer>=0 ? result.roadOfficer:2,
                    result.roadOfficer>=0 ? U"最後の一人まで脇道に入った。あの人たち、今度は困った時に道を教えるって言っていたよ。":
                    result.tracked ? U"旗は取った。兄者、あの街道は……見に行ける奴がいたら、探させてくれ。":
                    U"止まれって声、今度は一度で聞こえたぜ。",
                    result.roadOfficer>=0 ? U"避難した人々が、街道を守った隊に頭を下げる。":U"張飛は槍を下ろし、南を見た。"},
                {3,U"ここまでが俺たちの役目だ。負傷した者を先に運ぼう。旗はその間、俺が持つ。",
                    U"軍師は残る隊と帰る隊を呼び、陣の入口で見送る。"}};
        }
        else
            e.lines={
                {1,U"前陣へ入る隊を通せなかった。敵を引き受ける場所から、もう一度見よう。",U"関羽は広宗の地図を主人公の前へ戻す。"},
                {3,U"誰を先に行かせ、誰を待たせるか。今度は、その順を出る前にお前たちと合わせる。",
                    U"軍師は敵の旗の手前に、三人の駒を置き直した。"}};
        return e;
    }
}
