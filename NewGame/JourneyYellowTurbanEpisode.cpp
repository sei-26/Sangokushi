#include "JourneyEpisode.hpp"
#include "JourneyCampaign.hpp"
#include "StrategistJourney.hpp"

namespace frontline
{
    JourneyEpisode BuildYellowTurbanEpisode(const StrategistJourney& j)
    {
        const auto beat=CampaignBeat(j);
        JourneyEpisode e;
        e.title=beat.phase;
        e.place=U"一八四年・黄巾の乱 ／ 広宗郊外";
        e.setting=beat.change;
        e.question=beat.next;
        if(j.stage==JourneyStage::Preparation)
            e.lines={
                {-1,U"一八四年。張角に従う人々は黄巾をしるしに各地で挙兵した。劉備は校尉・鄒靖に従い、義勇兵を率いて戦いに加わった。",
                    U"史実の戦いを背景に、義勇軍の別働隊の役目を描く。"},
                {0,U"鄒靖殿から、前陣を攻める役目を預かった。向こうの旗の下にも、昨日まで鍬を持っていた者がいる。追い回す戦にはしたくない。",
                    U"劉備は広宗の地図を広げる。前陣の東にも、街道が続いている。"},
                {2,U"正面の旗は俺が倒す。……と言いたいが、南のあの隊、まだこっちを見てねえな。",
                    U"張飛が手を止め、南から前陣へ伸びる道を指でなぞる。"},
                {1,U"ならば、我らがここで敵を引き受ける。翼徳、お前が抜けるのは軍師の合図を聞いてからだ。",
                    U"関羽は林に駒を置く。もう一つの駒を、張飛へ渡した。"},
                {3,U"守備隊を前陣から離す。その隙に一隊を入れる。旗が替わったら、戻れと俺が言う。聞こえるところにいてくれ。",
                    U"主人公が二つの道に指を置く。三人がうなずいた。"}};
        else if(j.stage==JourneyStage::Complete)
            e.lines={
                {-1,U"張角はすでに没していた。その年の冬、皇甫嵩は広宗で張梁の軍を破り、続いて下曲陽で張宝の軍を破った。",
                    U"一八四年・冬。各地の反乱はなお続くが、張角の一族が率いた大きな蜂起は崩れた。"},
                {0,U"鄒靖殿に従った働きで、安喜の尉を任されたよ。今度はあの町で、戦が終わったあとの人の暮らしを見てみたい。",
                    U"劉備が辞令を置く。畳まれた軍旗の脇に、初めて役所の印が並ぶ。"},
                {2,U"お役人かよ、兄者が！ ……まあ、村で話を聞くのは、いつもと変わらねえか。",
                    U"張飛は笑い、旅支度の袋を肩にかける。"},
                {3,U"行こう。いつかまた兵を動かすとき、地図の中で何を守るか、思い出せるように。",
                    U"主人公は広宗の地図を折った。第一章・完。"}};
        else if(j.won)
            e.lines={
                {-1,U"黄巾の前陣に義勇軍の旗が立った。官軍の隊列が、その脇を抜けて前へ出る。",U"広宗郊外。前陣の占領が確かめられる。"},
                {2,U"止まれって声、今度は一度で聞こえたぜ。……まだ行けると思ったけど、皆もこっちを見てた。",
                    U"張飛は槍を下ろし、戻る隊が通る分だけ場所を空けた。"},
                {3,U"ここまでが俺たちの役目だ。負傷した者を先に運ぼう。旗はその間、俺が持つ。",
                    U"軍師は残る隊と帰る隊を呼び、陣の入口で見送る。"}};
        else
            e.lines={
                {1,U"前陣へ入る隊を通せなかった。敵を引き受ける場所から、もう一度見よう。",U"関羽は広宗の地図を主人公の前へ戻す。"},
                {3,U"誰を先に行かせ、誰を待たせるか。今度は、その順を出る前にお前たちと合わせる。",
                    U"軍師は敵の旗の手前に、三人の駒を置き直した。"}};
        return e;
    }
}
