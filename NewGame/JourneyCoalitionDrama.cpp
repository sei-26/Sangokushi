#include "JourneyEpisode.hpp"
#include "StrategistJourney.hpp"
#include "JourneyStrategicResponse.hpp"

namespace frontline
{
    JourneyEpisode BuildCoalitionGrandEpisode(const StrategistJourney& j)
    {
        const bool retreat=j.coalitionPlan==CoalitionPlan::Protect;
        const auto& c=j.battleReview.grand.coalition;
        JourneyEpisode e{U"第二章　汴水・並び立つ旗",U"一九〇年・汴水 ／ 史実を背景にしたIFの会戦",
            U"曹操はすでに対岸へ進んだ。張邈が送った援軍には、南から徐栄軍が迫る。",j.ObjectiveBrief()};
        if(j.stage==JourneyStage::Preparation)
            e.lines={
                {CaoCao,U"誰も出ぬなら、俺が出る。……だが軍師、独りで勝てると思って来たわけではない。向こうで、お前たちの旗を待つ。",U"曹操の先行隊が汴水を渡る。北と南、二つの橋がある。"},
                {ZhangMiao,U"孟徳に兵を送った。衛茲の隊だ。だが南から回られれば、彼らは橋へ戻れぬ。前へ進む者と、帰す者。どちらにも旗が要る。",U"張邈が、援軍の位置へ駒を置く。"},
                {-1,U"史実では、曹操はこの汴水で徐栄に敗れた。義勇軍の従軍と二つの作戦は、この物語のIFである。",U"川向こうに徐栄軍の陣。南の林から別働隊が動く。"},
                {1,retreat ? U"南の包囲隊を崩す。援軍の隣へ届くまで、救ったとは言えぬ。帰る橋を、こちらの兵で塞ぐな。":U"橋を渡っただけでは孤立が増える。曹操の前陣へ旗を入れ、援軍の退路にも一隊を残せるか考えよう。",U"関羽が二つの橋と対岸の旗をつなぐ。"},
                {2,retreat ? U"連れ帰るって決めたんだな。なら、追い払った敵をどこまでも追うなってことだろ。わかった、俺が橋の向こうで待つ！":U"今度はでかい旗の隣で暴れられるな！ 軍師、向こうへ渡る合図だけは聞き逃さねえぞ！",U"張飛が軍師の肩を叩く。"},
                {3,retreat ? U"曹操殿も、張邈殿の兵も連れて帰る。勝った数より、並んで戻る旗を見たい。南の包囲を開け！":U"曹操殿の孤軍を、連合の先陣に変える。対岸へ旗を立てるぞ。渡った後まで、俺が引き受ける！",U"主人公が二つの橋へ伝令を放つ。"}};
        else if(j.won)
            e.lines={
                {CaoCao,retreat ? U"退くとは、こんなに難しいものだったか。……軍師、あの橋で待っていた旗を、俺は忘れん。":U"独りで進んだ時には見えなかった。隣に旗が一本あるだけで、こんなに先が見えるとはな。",U"曹操が、帰ってきた軍師の顔を見る。"},
                {ZhangMiao,c.rescuedOn && c.reliefReturned>0 ? U"衛茲の兵が戻った。お前たちが開けた道を、彼らが今度は案内する。孫堅へ向かうなら、うちの者も連れていけ。":U"孟徳の旗は残った。だが、私が送った隊の声も聞いてほしかった。次の軍議には、あの南の道を消さずに持ってこい。",U"張邈は南の橋へ目を向ける。"},
                {0,U"旗の数では、帰ってきた兵の顔はわからないね。名前を聞いてから休もう。次の道も、ここから続いている。",U"劉備は、最後尾の兵に水を渡す。"},
                {3,U"次は、南の孫堅殿だ。今日つないだ旗も、届かなかった旗も、地図に残して行こう。",U"汴水の記録の隣に、陽人の地図が広げられた。"}};
        else
            e.lines={{CaoCao,U"合図は聞こえた。届かなかった道を、今度は一緒に見よう。兵をまた出すなら、同じ橋へ同じようには並べぬ。",U"汴水からの撤収。曹操の使者が軍師の陣を訪ねる。"},
                {3,U"戻れた者の話を先に聞く。南か北か、どこで離れたか。それから、次の渡り方を決める。",U"主人公は兵の名と、最後に見た場所を記した。"}};
        const int veteran=GuangzongVeteranOfficer(j);
        if(j.stage==JourneyStage::Debrief && j.won && c.rescuedOn && c.reliefReturned>0 && c.rescuedBy>=0 && c.rescuedBy<3 && e.lines.size()>3)
        {
            e.lines[2]={c.rescuedBy,c.rescuedBy==1 ?
                U"南で待っていた兵の目を覚えている。軍師、お前があの道へ私を出したから、こうして同じ岸へ戻れた。":c.rescuedBy==2 ?
                U"橋の向こうで、こっちの旗を見て笑った奴がいたんだ。軍師、見ただろ？ ああいう顔を、俺はまた連れて帰りてえ！":
                U"南へ届いた時、待っていた兵が旗を振ってくれた。軍師、君が選んだ道で、彼らとここに立てている。",
                U"救援を届けた武将が、戻った援軍の兵を迎える。"};
            e.lines[3]={3,retreat ? U"南へ届き、同じ岸へ戻った。今日、俺たちが変えたのは、この旗が次へ進めることだ。次は孫堅殿へつなごう。":
                U"曹操殿と攻め、南へも道をつないだ。今日並んだ旗を、次は孫堅殿へ届けよう。あの橋の先まで、俺たちの一手だ。",
                U"主人公は、救援を届けた武将の名を汴水の地図へ記す。"};
        }
        if(j.stage==JourneyStage::Preparation && veteran>=0 && e.lines.size()>4)
            e.lines[4]={veteran,veteran==2 ? U"軍師、見ろよ！ 広宗で引っ張り出した連中だ！ 今度は俺の後ろを守るってよ。……なら、背中は任せた！":
                veteran==1 ? U"あの北の旗だ。広宗で救った兵が、今度は我らの背を支えると言う。軍師、お前の一手は、まだ終わっていなかったのだな。":
                U"広宗の北で救った兵たちが来てくれた。『今度はこちらが支えます』とね。軍師、あの日選んだ道が、今日ここへつながった。",
                U"広宗の生還兵が連合の後陣へ合流し、救援した武将の旗の後ろへ並ぶ。戦場では間を保ち、帰る隊へ道を譲る。"};
        return e;
    }
}
