#include "StrategistJourney.hpp"
#include "JourneyEpisode.hpp"
namespace frontline
{
    std::vector<JourneyDialogueLine> JourneyCouncilConversation(const StrategistJourney& j,int who)
    {
        if(j.mission==LuoyangMission)
        {
            const bool west=j.luoyangPlan==LuoyangPlan::WesternDepot;
            const char32_t* advice[]={west ? U"倉に入ったら、敵の旗より荷の数を先に確かめよう。兵糧を運び出してこその勝ちだよ。":
                U"門前の旗を目印に孫堅殿が入る。追撃より、最後にそこへ残る隊を頼みたい。",
                U"狭い道に全員を出すな。林で敵を受ける隊と、目標へ入る隊を分けるのだ。",
                west ? U"荷駄陣の後ろに別の隊がいる。俺が引き受けるから、米を取りに行く奴は止まるなよ！":
                    U"城壁の横を回る。正面の敵が俺の方を向いたら、誰かが門へ走ってくれよ！"};
            return {{who,advice[who]},{3,U"敵が動いた方を見て合図を出す。最後に旗を立てる隊も残す。"}};
        }
        if(j.HasSunJian())
        {
            const char32_t* advice[]={U"孫堅殿と合流するまでは、辻を取っても前へ出ない。私が旗を残そう。",
                U"呂布を林へ引けば、馬は平地ほど走れぬ。南へ向かわせぬよう、私がこちらから引き受ける。",
                U"南で孫堅が止まったら俺を呼べ。あいつの前の敵をどければ、辻まで一気に来られるぞ。"};
            return {{who,advice[who]},{3,U"辻と南道、両方を見て合図を出す。敵を追いすぎるな。"}};
        }
        if(j.mission==CoalitionMission)
        {
            const auto episode=BuildJourneyEpisode(j);
            return {{who,episode.lines[who].text},{3,episode.lines.back().text}};
        }
        if(j.mission==YellowTurbanMission)
        {
            if(who==0) return {{0,U"官軍の役目は前陣を取るところまでだ。落ちた旗を追うより、戻る者を迎えたい。"},
                {3,U"占領役は一隊でいい。残りは帰る道を残そう。"}};
            if(who==1) return {{1,U"正面の守備を林へ引ければ、南から前陣へ届く。私を使うなら、合図を先に決めておけ。"},
                {3,U"合図まで待ってくれ。南の敵が動いたら、俺が先に知らせる。"}};
            return {{2,U"南には反撃隊がいるぜ。先頭に出るなら、こいつを押しのける手を残しとく。"},
                {3,U"前陣に着く前に全部使うなよ。誰を通すかは、俺が呼ぶ。"}};
        }
        if(j.mission==0 && j.IsRescue() && j.convoyRoute==JourneyConvoyRoute::SouthernWood)
        {
            if(who==0) return {{0,U"南の林を通れる者を、季安が見つけてきたよ。"},
                {3,U"案内料百二十。道は少し長くなる……か。"},
                {0,U"私を見るより、車を見て決めてほしい。私は君の決めた道を守る。"},
                {3,U"なら、正面に全員は出さない。出口で待つ隊を作る。"}};
            if(who==1) return {{1,U"林道を選んだな。では、私はどちらを見る。"},
                {3,U"正面の敵を引き受けてほしい。出口へ回す隊の、時間を作る。"},
                {1,U"敵の旗が残っていても、策は成る。そういうことか。"},
                {3,U"ああ。車が通った時に、勝ったと言ってくれ。"}};
            return {{2,U"林の向こうで待ってろ、だあ？ ここに敵がいるのにか？"},
                {3,U"その敵より先に、車が通る場所へ行ってほしい。お前に頼む。"},
                {2,U"……俺を選んで言ってんだな。"},
                {3,U"出口は任せる。呼ぶまで、道を空けて待っててくれ。"},
                {2,U"おう！ 遅れんなよ、軍師！"}};
        }
        if(j.mission==0)
        {
            if(who==0) return {{0,U"おや、見事な泥の鎧だね。張飛が、新しい豪傑を連れてきたと騒いでいたよ。"},
                {3,U"豪傑なら、車輪ひとつに三人も要らないさ。……最後は張飛が一人で持ち上げたけど。"},
                {0,U"はは、腕比べは彼に任せよう。君には、皆の力が届く道を見つけてほしい。頼めるかな。"},
                {3,U"兵を動かしたことは、まだない。"},
                {0,U"人が通れる道は見てきた。私は、そこから頼みたいんだ。"}};
            if(who==1) return {{1,U"ほう。私の駒を、ずいぶん面白い所へ置いたな。"},
                {3,U"嫌か？ そこからなら、張飛の横っ腹を守れると思ったんだ。"},
                {1,U"嫌なら駒を戻している。……よい目だ。では、後ろの車は誰に任せる。"},
                {3,U"褒めた後に、すぐ難問か。お前、教えるのが厳しいな。"},
                {1,U"君なら考えられると思ったのだ。遠慮はいらぬ。私の力、存分に使え。"}};
            return {{2,U"俺はどいつをぶっ飛ばせばいい？ 一番でけえ旗か？"},
                {3,U"まだ決めてない。先に、お前がどこまで走れるか聞かせてくれ。"},
                {2,U"どこまでも、だ！"},
                {1,U"戻ってくる距離を聞いている。"},
                {3,U"……今ので、だいたい分かった。戻れって言ったら聞けよ。"},
                {2,U"おう。聞こえるくらい、でけえ声で呼べよ軍師！"}};
        }
        if(j.CurrentPledge()==JourneyPledge::Preserve)
        {
            if(who==0) return {{0,U"兵を連れ帰ると言ったね。私は、その話から軍議を始めたい。"},
                {3,U"誰を前へ出すかより、誰を最後に戻すかを先に決める。"},
                {0,U"なら、私も最後の列へ。君一人には背負わせないよ。"},
                {3,U"……そう言ってもらえると、命令しづらいな。"},
                {0,U"しづらいまま、決めてくれ。それが君を信じるということだ。"}};
            if(who==1) return {{1,U"帰す兵の数を、もう一度。"},
                {3,U"出陣する兵の、少なくとも九割だ。護衛も数える。"},
                {1,U"承知した。無理な追撃を止める時は、私の名を使え。"},
                {3,U"関羽が言ってたから、って？"},
                {1,U"最後は君が決めろ。……名前を貸すくらいは、してやる。"}};
            return {{2,U"帰ってこい、か。突っ込めより難しい注文だな。"},
                {3,U"お前がいない次の軍議を、考えたくない。"},
                {2,U"……お前、そういうの、さらっと言うなよ。"},
                {3,U"だから、戻れと言ったら戻れ。約束だ。"},
                {2,U"分かった！ その代わり、飯は多めに残しとけ！"}};
        }
        if(j.CurrentPledge()==JourneyPledge::Coordinate)
        {
            if(who==0) return {{0,U"次は皆をつなぐ。君はそう言ったね。"},
                {3,U"一人が戦ってる間に、次の一人が間に合う場所を作る。"},
                {0,U"私は、最初の一人にもなれる。君が必要だと思う所へ置いてくれ。"},
                {3,U"主将を囮に、って言ってもか。"},
                {0,U"帰す策も、付けてくれるのだろう？"}};
            if(who==1) return {{1,U"合図を待つ。その間に敵が来たら、どうする。"},
                {3,U"無理なら中止だ。俺の策より、お前の兵を残す。"},
                {1,U"……中止を言えるなら、待つ価値がある。"},
                {3,U"行ける時は、迷わず呼ぶ。その声だけは信じてくれ。"}};
            return {{2,U"今度こそ、俺の出番を忘れるなよ！"},
                {3,U"忘れない。だが最初に飛び出したら、策がつながらない。"},
                {2,U"分かってるって。……足がむずむずするんだよ。"},
                {1,U"なら、私の後ろを走れ。"},
                {3,U"決まりだ。二人の間は、俺の合図でつなぐ。"}};
        }
        // Older saves have no new promise. Preserve their progress without inventing one.
        if(who==0) return {{0,U"季安が、また君の策で道を通りたいそうだ。"},
                {3,U"今度は、運ぶものも重いな。"},
                {0,U"前の戦いで残したものが、ここにある。君なら、何を先に守る？"},
                {3,U"出る前に決める。今度は、皆の前で。"}};
        if(who==1) return {{1,U"前の策を、もう一度そのまま使うつもりか。"},
                {3,U"相手が変われば、役も変える。お前を守りに置くこともある。"},
                {1,U"よい。守りは、攻め残った者の仕事ではない。"},
                {3,U"そこを任せられるから、前へ出す隊を決められる。"}};
        return {{2,U"さあ軍師、今度はどこだ！"},
                {3,U"まだ走るな。今回は待つ場所も教える。"},
                {2,U"分かってるよ。……お前が呼ぶなら、ちゃんと待つさ。"},
                {3,U"その一言が、いちばん頼もしいな。"}};
    }
}
