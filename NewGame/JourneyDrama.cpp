#include "StrategistJourney.hpp"
namespace frontline
{
    std::vector<JourneyDialogueLine> JourneyCouncilConversation(const StrategistJourney&,int);
    std::vector<JourneyDialogueLine> JourneyConversation(const StrategistJourney& j,int officer)
    {
        const int who=std::clamp(officer,0,2);using Lines=std::vector<JourneyDialogueLine>;
        if(j.stage==JourneyStage::Preparation) return JourneyCouncilConversation(j,who);
        if(j.stage!=JourneyStage::Debrief && j.stage!=JourneyStage::Complete) return {};
        const auto& s=j.history[j.mission].story;Lines lines;
        if(j.withdrawn)
        {
            if(who==0) lines={{0,U"引くと決めたんだね。まず、座ろう。君の手、まだ震えている。"},
                {3,U"俺が退けと言った。途中で見捨てたと思ってる兵もいる。"},
                {0,U"なら、明日も顔を見せよう。命令した人が、帰ってから姿を消してはいけない。"},
                {2,U"おい軍師。飯だ。反省するにも腹は減るんだよ。"},
                {3,U"……一緒に、食っていいのか。"},
                {0,U"君も、帰ってきた一人だろう。"}};
            else if(who==1) lines={{1,U"引く合図が聞こえた。あれは、君の声か。"},
                {3,U"ああ。声が裏返ったけどな。"},
                {1,U"届いた。それでよい。次は、引く場所を戦う前に教えておけ。"},
                {3,U"逃げる算段まで、俺の仕事か。"},
                {1,U"皆を帰す算段だ。言葉を間違えるな。"}};
            else lines={{2,U"戻れって言われた時ゃ、腹が立った。まだやれたんだぞ。"},
                {3,U"俺には、戻れなくなるように見えた。"},
                {2,U"……だから戻ったんだよ。お前、いつも後ろ見てんだろ。"},
                {3,U"それ、信じてくれたってことか。"},
                {2,U"言わせんな！ 次は飯が冷める前に合図しろ！"}};
        }
        else if(!j.won)
        {
            if(who==0) lines={{0,U"敵の旗より、車の方を見ていたかい。"},
                {3,U"勝てば、全部片づくと思っていた。……俺の間違いだ。"},
                {0,U"その言葉は、私より先に、待っていた人へ言おう。"},
                {3,U"次は、最後に誰が残るかまで決めて出る。"},
                {0,U"うん。私も、その一人に数えてくれ。"}};
            else if(who==1) lines={{1,U"言い訳を聞きに来たのではない。どこで策が崩れた。"},
                {3,U"敵を追う隊と、残る隊を決めていなかった。"},
                {1,U"では、次は私を残せ。守る仕事に余りの兵を回すな。"},
                {3,U"……一番頼れる隊を、守りに回すんだな。"},
                {1,U"ようやく、私の顔を見て話したな。"}};
            else lines={{2,U"俺がもっと早く突っ込んでりゃ、間に合ったか？"},
                {3,U"違う。俺が、行けと言う場所を間違えた。"},
                {2,U"一人で全部かぶんな。お前が黙っちまう方が困る。"},
                {3,U"なら次は、無茶だと思ったら言ってくれ。"},
                {2,U"言うぞ。でかい声でな。耳、鍛えとけよ！"}};
        }
        else if(s.recorded && s.pledge!=JourneyPledge::None && !s.pledgeKept)
        {
            if(who==0) lines={{0,U"任務は果たした。けれど、出る前に君が言ったことも覚えている。"},
                {3,U"約束まで、勝利で消せるわけじゃないな。"},
                {0,U"君の言葉を頼りに前へ出た人がいる。次は、背負える言葉を選ぼう。"},
                {3,U"……今度は、言った俺が最後まで見届ける。"}};
            else if(who==1) lines={{1,U"勝った。そこは認める。だが、君の約束は果たされていない。"},
                {3,U"勝つために、仕方なかった。そう言えば、納得するか。"},
                {1,U"しない。そう言うしかなかった場所を、次に作らぬために話している。"},
                {3,U"……兵を出す前の俺から、やり直す。"},
                {1,U"その返事なら、聞く価値がある。"}};
            else if(s.pledge==JourneyPledge::Preserve) lines={{2,U"みんな連れて帰るって、お前、言ったよな。"},
                {3,U"ああ。俺が言った。戻らなかった兵のことも、勝ったからで済ませない。"},
                {2,U"……俺だけ帰って、飯がうまいわけねえだろ。"},
                {3,U"次は、退く場所と合図を先に決める。お前にも止めてほしい。"},
                {2,U"言ったな。次は俺の声も聞けよ、軍師。"}};
            else lines={{2,U"軍師。出る前の話、忘れたわけじゃねえよな。"},
                {3,U"忘れてない。俺の合図を、当てにしてくれてたんだな。"},
                {2,U"当たり前だろ！ 当てにしてなきゃ、あんな所まで走るかよ。"},
                {3,U"次は、呼んだら必ずつながる策にする。"},
                {2,U"……おう。今度こそ、置いてくなよ。"}};
        }
        else if(s.costly)
        {
            if(who==0) lines={{0,U"勝った、と伝えてきた。あとは何を言えばよかったのだろうね。"},
                {3,U"俺が命令した。戻らなかった兵も、俺の策で前に出た。"},
                {0,U"名前まで、ひとりで背負わなくていい。私も一緒に聞く。"},
                {3,U"なら次の軍議で、帰す兵の数から話したい。"}};
            else if(who==1) lines={{1,U"道は開いた。……だが、戻った列が短い。"},
                {3,U"あの一手を通すには、前へ出てもらうしかなかった。"},
                {1,U"盤上なら、それで済む。ここでは、空いた場所に名がある。"},
                {3,U"勝ったから正しかった、とは言わない。次の策で答える。"},
                {1,U"言ったな。私は、その答えを待つ。"}};
            else lines={{2,U"勝ったんだよな。なのに、どうしてこんなに静かなんだよ。"},
                {3,U"俺が、勝った後の顔まで考えていなかった。"},
                {2,U"次は……あいつらの分まで、なんて言うなよ。"},
                {3,U"ああ。今いる兵を、ちゃんと連れ帰る。"},
                {2,U"それだ。それを聞きたかった。"}};
        }
        else if(s.protectedPeople)
        {
            if(who==0) lines={{0,U"季安が君を探していたよ。礼を言う相手を間違えた、と。"},
                {3,U"間違えた？ 敵の旗を倒したのは、あいつらだろ。"},
                {0,U"最後の車が通るまで、道を残した人に会いたいそうだ。"},
                {2,U"おい軍師！ 礼を言うなら、俺も呼べよ！"},
                {3,U"呼んでるだろ。……お前、車の人たちが気になるんだな。"},
                {0,U"ふふ。それを見つけるのも、君の仕事だね。"}};
            else if(who==1) lines={{1,U"敵が崩れても、任務は続いた。いつ終わったと思った。"},
                {3,U"最後の車が出口を抜けた時だ。旗の数だけじゃ、終われなかった。"},
                {1,U"……私も、同じものを見ていた。"},
                {3,U"だったら、先に言ってくれよ。俺、ずっと迷ってたんだぞ。"},
                {1,U"君が決めるのを待った。軍師。次も、その目で決めろ。"}};
            else lines={{2,U"なあ、気がついたら、あの車ずいぶん先へ行ってたな。"},
                {3,U"お前たちがいてくれたから、俺は車の道を見ていられた。"},
                {2,U"……そういう言い方、ずるくねえか。もう一回行きたくなるだろ。"},
                {0,U"では、荷下ろしを頼めるかな。"},
                {2,U"戦の話をしてんだよ、兄者！"},
                {3,U"俺も手伝う。軍師の命令、だろ。"}};
        }
        else if(s.pledgeKept)
        {
            if(who==0) lines={{0,U"出る前の言葉、ちゃんと帰ってきたね。"},
                {3,U"口にした時より、ずっと重かった。"},
                {0,U"それでも果たした。次に君の声を聞く兵は、今日のことも聞いている。"},
                {3,U"なら、次も軽々しく言わない。みんなの前で決める。"}};
            else if(who==1) lines={{1,U"約束を守ったな。……今日は、それだけを言いに来た。"},
                {3,U"え、それだけか？ もっと何か、間違えた所とか。"},
                {1,U"褒めている。そう何度も言わせるな。"},
                {2,U"おい軍師！ 顔、にやけてるぞ！"},
                {3,U"にやけてない。……少ししか。"}};
            else if(s.pledge==JourneyPledge::Preserve) lines={{2,U"帰った兵、数えたか？ 俺だけ忘れてんじゃねえぞ。"},
                {3,U"その声がするうちは、忘れようがない。"},
                {2,U"そうかよ！ ……次も、この人数で飯食いてえな。"},
                {3,U"ああ。そのために、次も俺が決める。"}};
            else lines={{2,U"聞こえたぞ、お前の合図。今度は迷わず走れた。"},
                {3,U"合図だけじゃない。帰るところまで、見てた。"},
                {2,U"知ってるよ。だから背中、預けたんだ。"},
                {3,U"……次も、俺の声を聞いてくれ。"},
                {2,U"おう。裏返ったって聞き逃さねえよ。"}};
        }
        else if(s.coordinatedOfficers)
        {
            if(who==0) lines={{0,U"君の合図で、ばらばらだった足音がそろった。"},
                {3,U"誰か一人が強ければいいと思ってた。違ったんだな。"},
                {0,U"強い者が、どこへ走れるか。その道を作った人も、ここにいる。"},
                {3,U"……俺も、あの戦いの中にいたってことか。"},
                {0,U"いちばん声を枯らしていただろう？"}};
            else if(who==1) lines={{1,U"先の一手だけでなく、次に誰が動くかまで見ていたな。"},
                {3,U"関羽なら間に合わせると思った。頼りすぎたか。"},
                {1,U"頼ることと、任せきることは違う。今日の合図には、行く先があった。"},
                {3,U"なら次は、引く先まで付けて頼む。"}};
            else if(!(s.coordinatedOfficers&4)) lines={{2,U"おい軍師。二人ばっかりつないで、俺の出番はどこだ？"},
                {3,U"次も立っていてくれないと、困るんだ。"},
                {2,U"……うまいこと言いやがって。次は俺も混ぜろよ！"},
                {3,U"ああ。お前が走る道も、俺が作る。"}};
            else lines={{2,U"あの合図、よかったじゃねえか。体が勝手に前へ出たぞ。"},
                {3,U"勝手に出るなよ。俺が合わせた意味がなくなる。"},
                {2,U"細けえな！ ……でも、ちゃんと見てたんだな。"},
                {3,U"見てなきゃ、お前をあそこへは出さない。"},
                {2,U"よし。次も呼べ。遅れんなよ、軍師！"}};
        }
        else
        {
            if(who==0) lines={{0,U"帰ってきた兵が、君のことを話していた。"},
                {3,U"派手な策は、使えなかったけどな。"},
                {0,U"明日も飯が食える、と言っていたよ。それは小さな戦果かな。"},
                {3,U"……次の軍議にも、その兵の席を空けておこう。"}};
            else if(who==1) lines={{1,U"必要な所で戦い、余計な所へ兵を出さなかった。"},
                {3,U"臆病だっただけかもしれない。"},
                {1,U"臆病と呼ぶ者には、帰った兵の顔を見せてやれ。"},
                {3,U"関羽がそんなこと言うと、反論できないな。"},
                {1,U"そのために言った。"}};
            else lines={{2,U"まだ戦えたぞ、俺は。"},
                {3,U"知ってる。だから、次の戦いにも残っていてほしい。"},
                {2,U"……そう来るか。うまくなったな、俺の止め方。"},
                {3,U"止めるのも走らせるのも、俺の仕事らしいからな。"}};
        }
        if(j.won && j.IsRescue() && j.convoyRoute==JourneyConvoyRoute::SouthernWood)
            lines.push_back({3,U"林の道を選んだ。出口で待つ隊を信じた。……この勝ち方を、次も覚えておく。"});
        if(s.reply!=JourneyPledge::None)
        {
            lines.push_back({3,s.reply==JourneyPledge::Preserve ? U"次は、みんなを連れて帰る。そのために戦う場所を俺が決める。":U"次は一人で片づけさせない。俺が合図を出して、皆をつなぐ。"});
            lines.push_back({who,who==0 ? U"うん。私は、君が守ると決めたものを一緒に守る。":who==1 ? U"言葉は預かった。次の戦場で、答えを見せてもらう。":U"おう！ 約束だぞ。俺もその策に数えとけよ！"});
        }
        return lines;
    }
}
