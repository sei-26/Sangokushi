#include "JourneyEpisode.hpp"
#include "StrategistJourney.hpp"
namespace frontline
{
    void BuildEpisodeAftermath(const StrategistJourney& j,JourneyEpisode& e)
    {
        e.place=U"一八四年・黄巾の乱　／　帰陣、野営地";
        e.setting=U"戦場では聞こえなかった音が戻る。鍋の蓋、縄をほどく手、名を呼んで返事を待つ声。";
        e.question=U"この勝ち方を、次の自分へ引き継げるか。";
        const auto& s=j.history[j.mission].story;
        const int initial=j.deployed+j.convoyEscort;
        const bool costly=s.recorded ? s.costly : initial>0 && j.history[j.mission].casualties*4>=initial;
        int wins=0;for(const auto& h:j.history) if(h.completed && h.won) ++wins;
        if(j.stage==JourneyStage::Complete)
        {
            e.title=wins==3 ? U"序章終幕　名を呼ぶ者たち":U"幕の終わり　帰る席";
            e.lines={{-1,wins==3 ? U"泥の道から、米俵の道へ。そして、小さな火を守る戦いへ。三つの采配が、同じ野営地へ帰ってきた。":
                U"任された役目を終え、軍師は野営地へ戻った。戦場の外では、次の朝を迎える支度が始まっている。",U"使い込んだ地図を、灯りの下へ広げる。"}};
            int loss=0;for(const auto& h:j.history) loss+=h.casualties;
            if(loss>0) e.lines.push_back({3,wins==3 ? U"三度とも、何かを置いてきた。この地図を、きれいなまま飾る気にはなれない。":U"今日の戦いで、置いてきたものがある。この地図を、きれいなまま飾る気にはなれない。",U"主人公は、消しかけた印へもう一度指を置く。"});
            else e.lines.push_back({3,wins==3 ? U"三度とも連れ帰れた。次も同じにできるとは、まだ言えない。だから、この地図を持っていく。":U"今日は連れ帰れた。次も同じにできるとは、まだ言えない。だから、この地図を持っていく。",U"主人公は、使い込んだ地図を丁寧に折る。"});
            if(j.history[0].rescued) e.lines.push_back({4,U"あの時、車を待った軍師だって。皆、もうあなたをそう呼んでますよ。",U"季安が、最初の日と同じ車輪を叩いた。"});
            else if(j.history[0].completed) e.lines.push_back({4,U"道を開いたあの日から、荷を運ぶ連中の話に、あなたの名が出るようになりました。",U"季安は今度は、帽子を取って言う。"});
            else e.lines.push_back({4,U"荷を運ぶ者にも、今日の戦いの話が届いています。軍師さん、戻ってきたんですね。",U"季安は、隣の席を空けてみせる。"});
            e.lines.insert(e.lines.end(),{
                {2,U"おい、軍師！ 飯だ！ ……何だよ、また難しい顔して。",U"張飛の声だけは、最初の日と変わらない。"},
                {1,U"来い。振り返る時間まで捨てろとは言わぬ。だが、席は空けてある。",U"関羽は椀を一つ、仲間の間へ置く。"},
                {0,U"私は、いつかこの乱世を終わらせたい。君はその時、何を守る軍師でいたい？",U"天下という言葉が、初めて同じ食卓に置かれる。"},
                {3,U"今はまだ、そこにいる人の顔を忘れない軍師でいたい。……一緒に考えさせてくれ。",U"主人公は、用意されていた席に座る。"},
                {-1,U"名を呼ぶ者がいる。戻る席がある。この軍師の物語は、ここから始まる。",U"序章・了。火の向こうには、まだ見ぬ旗が揺れていた。"}});
            return;
        }
        if(j.withdrawn || !j.won)
        {
            e.question=U"果たせなかった戦いを、誰と語り直すのか。";
            e.lines={
                {-1,j.withdrawn ? U"引く合図は、主人公が出した。軍旗が戻っても、任務が果たされたわけではない。":U"任された役目は、果たせなかった。報せる言葉を探している間にも、夜は来た。",U"軍議の椀は伏せられたまま、誰も地図を片づけない。"},
                {3,j.withdrawn ? U"俺が戻れと言った。置いてきた仕事も、俺の命令の結果だ。":U"地図の上では足りていた。現場で足りなくなったものを、見直したい。",U"主人公は、誰の顔から見ればよいか迷う。"},
                {1,U"なら、ここから始める。次は何を捨て、何を残す。",U"関羽は、失敗した手を消さずに囲んだ。"},
                {2,U"反省は聞く。けど、いなくなるなよ。呼んでも返事がねえ軍師は困る。",U"張飛は隣の椀を、主人公の方へ押す。"},
                {0,U"今夜は、ここにいよう。次の策は、同じものを見た者と話すんだ。",U"劉備が灯りを寄せる。地図の端が、また見える。"}};
            return;
        }
        e.lines.push_back({-1,U"任務は果たされた。けれど、勝利という一語で、その日のすべてを語ることはできなかった。",U"旗を下ろした後にも、人々の仕事は続く。"});
        if(costly)
            e.lines.insert(e.lines.end(),{
                {2,U"飯、こんなに余るはずじゃなかったんだがな。",U"張飛は鍋を持ったまま、配る順を数え直す。"},
                {3,U"出した兵の数は覚えていた。戻ってからの席まで、数えていなかった。",U"主人公は地図を閉じかけて、手を止める。"},
                {1,U"閉じるな。誰を前へ出したかも、戻す時をどこに置いたかも、そこに残っている。",U"関羽の声は小さい。誰も、その先を急がせない。"},
                {0,U"この勝利の報せは、私がする。君は、次の軍議へ来てくれ。そこから一緒に変えよう。",U"劉備は軍旗を自分で畳んだ。"}});
        else if(j.mission==0 && j.history[0].rescued)
            e.lines.insert(e.lines.end(),{
                {4,U"車輪が外れたんです。最後の所で。……あの時、まだ待っていてくれた。",U"季安は修理の終わった軸を、何度も確かめる。"},
                {3,U"旗は倒れていた。でも、車がまだだった。だから、終われなかった。",U"主人公の袖にも、同じ泥が乾いている。"},
                {2,U"礼ならこいつに言え。俺が追おうとしたら、でけえ声で止めやがった！",U"張飛は主人公の肩を叩き、今度は力を緩める。"},
                {0,U"今日は、帰る場所を残したね。私も、そういう勝ち方を覚えておきたい。",U"地図の隅に、小さな車の印が加わった。"}});
        else if(j.mission==1)
            e.lines.insert(e.lines.end(),{
                {4,U"荷は着きました。米を量る者が、もう待っています。",U"季安は戦果より先に、積荷の縄をほどく。"},
                {2,U"旗を奪ったわけでもねえのに、ずいぶん呼ばれるな。",U"荷を下ろすたびに、礼と次の仕事が飛んでくる。"},
                {1,U"あの米が尽きれば、槍を持つ者も立てぬ。それを守った。",U"関羽は槍を立てかけ、荷台へ手を掛けた。"},
                {3,U"だったら、軍師の仕事も荷下ろしまでか。張飛、そっちを持ってくれ。",U"主人公は地図を懐へ入れる。"},
                {2,U"おう！ そういう合図は早えじゃねえか！",U"今度は、皆の笑い声が重なった。"}});
        else if(j.mission==2)
            e.lines.insert(e.lines.end(),{
                {2,U"見えてたぞ、向こうの火。消えねえから、俺も待てた。",U"張飛は、離れていた仲間の顔を一人ずつ見る。"},
                {1,U"こちらからも、見えていた。待つと決めた者がいたから、守れた。",U"関羽は、燃え残った薪を火へ戻す。"},
                {3,U"離れていても、一つの策にできるんだな。……俺一人じゃ、絶対にできなかった。",U"主人公の声は、戦場で出した合図より小さかった。"},
                {0,U"だから、皆で戻ってこの話をしよう。次の地図を開く前に。",U"火の周りに、順に人が座っていく。"}});
        else e.lines.insert(e.lines.end(),{
                {4,U"道が空いた。ようやく、そう伝えられます。車を動かすのは、ここからです。",U"季安は帽子を直し、もう一度荷車の方を見る。"},
                {3,U"敵を退けて終わったと思いかけた。戦の外にも、まだ仕事があるんだな。",U"主人公も、その視線を追う。"},
                {0,U"君が開いた道だよ。その先を、誰が通るかも覚えていよう。",U"劉備は追撃の号令をしまい、荷車へ歩き出した。"}});
        if(s.recorded && s.pledge!=JourneyPledge::None)
        {
            if(s.pledgeKept) e.lines.push_back({1,U"出陣前の言葉も、果たしたな。結果だけでなく、それを見ていた者もいる。",U"関羽は、主人公が書いた約束を消さずに残す。"});
            else e.lines.push_back({1,U"だが、出る前の約束は果たしていない。勝った日にこそ、その話を残しておく。",U"喜びの声の中で、関羽だけが声を落とした。"});
        }
        if(s.reply!=JourneyPledge::None) e.lines.push_back({3,s.reply==JourneyPledge::Preserve ?
            U"次は、兵の九割を連れ帰る。護衛も数える。その言葉を、次の戦場まで持っていく。":
            U"次は、二隊以上の戦法をつなぐ。一人の働きに任せず、俺が皆の間へ合図を出す。",U"返答は、すでに交わした約束として記録されている。"});
        if(j.mission==0) e.lines.push_back({-1,U"道が開けば、運ぶものがある。次に軍師へ預けられるのは、名誉より重い米俵だった。",U"次幕へ――米と旗。"});
        else if(j.mission==1) e.lines.push_back({-1,U"米は届いた。今度は、離れた者たちをつなぐ火を守らねばならない。",U"次幕へ――消えない火。"});
        else e.lines.push_back({-1,wins==3 ? U"三つの役目を終えた軍師を、待つ声がある。地図の外に、帰る席ができていた。":U"任された役目を終えた軍師を、待つ声がある。地図の外に、帰る席ができていた。",U"次へ進むと、序章の終幕。"});
    }
}
