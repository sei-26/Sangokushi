#include "JourneyEpisode.hpp"
#include "StrategistJourney.hpp"
namespace frontline
{
    void BuildEpisodeCouncil(const StrategistJourney& j,JourneyEpisode& e)
    {
        e.place=U"一八四年・黄巾の乱　／　出陣前の義勇軍";
        if(j.mission==0)
        {
            e.setting=U"濡れた地図の端を、欠けた椀が押さえている。軍議の外では、車輪がまだ泥を噛んでいた。";
            e.question=U"敵の旗を折れば、誰の戦いが終わるのか。";
            e.lines={
                {-1,U"一八四年。黄巾の乱を背景に、これは、まだ名もない軍師の物語である。",U"地図より先に、車輪の軋む音がする。"},
                {4,U"馬も米も、出せと言われて出しました。今度は道まで、渡せと言うんですか。",U"季安は帽子を取らない。泥の付いた手だけを握り直す。"},
                {2,U"渡すかよ。向こうの旗を倒しゃ、道は空く！",U"張飛が立つ。椀の水が、地図の上へこぼれた。"},
                {1,U"座れ。道が空くことと、車が通り終えることは違う。",U"関羽は赤い印ではなく、その後ろの細い道を指す。"},
                {0,U"私は、この乱世を鎮めたい。……だが今、天下の話をしても、その車は動かないね。",U"劉備は椀をどけ、自分の袖で地図を拭いた。"},
                {4,U"天下より、今晩です。子どもが、車で待ってる。",U"軍議の外へ目をやる。誰も、すぐには答えない。"},
                {3,U"俺なら泥の浅い所は分かる。兵の動かし方は、まだ知らない。",U"主人公は、汚れた指を地図へ置く。"},
                {1,U"なら、誰の力が要る。分からぬ所を、黙って埋めるな。",U"関羽が、自分の駒を主人公の手元へ寄せる。"},
                {3,U"前へ出す隊だけじゃない。道に残す隊も、俺が決める。",U"車輪の音が止む。外から、誰かが車を押す声がする。"},
                {2,U"決めたら呼べ。押すのも、ぶっ飛ばすのも、俺は得意だ。",U"張飛はこぼした椀を拾い、照れくさそうに置き直した。"},
                {0,U"皆、聞いたね。この一戦の采配を、彼に預ける。責任は、私も負う。",U"将たちの目が、初めて同じ場所へ向く。"}};
            if(j.IsRescue()) e.lines.push_back({3,j.convoyRoute==JourneyConvoyRoute::SouthernWood ?
                U"南の林を行くなら、案内の費用と、出口を守る隊が要る。そこまで引き受けるか、ここで決める。":
                U"車ごと送り届けるなら、道が空いた後も守る隊が要る。そこまでを俺たちの戦にするか、ここで決める。",
                U"季安は返事を待つ。役目を選ぶのは、これからだ。"});
            else e.lines.push_back({3,U"退路を開くか、車の護送まで引き受けるか。敵を退けただけで全部が終わったとは言わない。俺が、任される役目を決める。",U"主人公は、まだ線を引かない。軍議で、自分の役目を決める。"});
            return;
        }
        // Earlier victories are remembered from actual history, including legacy saves without new story fields.
        const auto& previous=j.history[j.mission-1];
        e.setting=j.mission==1 ? U"旗は直された。だが、荷車の割れた軸は、まだ同じ縄で縛られている。":
            U"風で烽火が傾く。誰も口にしないまま、兵たちは帰り道にも目印を立てていた。";
        e.question=j.mission==1 ? U"名を上げるための勝利か。明日を食いつなぐための勝利か。":U"離れた仲間を、どこまで信じて待てるか。";
        const bool costly=previous.story.recorded ? previous.story.costly : previous.casualties>0 &&
            previous.casualties*4>=previous.survivors+previous.casualties;
        if(!previous.completed)
            e.lines.push_back({0,U"この役目を、君に任せたい。まず、誰をどこへ置くか。一緒に考えよう。",U"劉備が、まだ印のない地図を広げる。"});
        else if(costly)
            e.lines.push_back({1,U"前の戦いで、列は短くなった。今日は、その数を忘れた軍議にはさせぬ。",U"関羽は、空いた席の方へ地図を広げた。"});
        else if(previous.rescued)
            e.lines.push_back({4,U"あの車にいた子が、今朝は荷を結ぶのを手伝いました。あの時、待ってくれたからです。",U"季安が、ほどけないように縄を引く。"});
        else e.lines.push_back({0,U"前の道は開いた。だからこそ、次に運べるものがある。今日は、その先の話をしよう。",U"前の地図の上へ、新しい地図を重ねる。"});
        if(j.mission==1)
            e.lines.insert(e.lines.end(),{
                {2,U"兵糧か。こいつを届けりゃ、次はでかい戦ができるな！",U"張飛が米俵を軽く叩く。"},
                {4,U"戦をしない日にも、腹は減ります。",U"季安は笑わず、俵の口を結び直した。"},
                {2,U"……そうかよ。じゃあ、なおさら落とせねえな。",U"張飛が、今度は静かに俵を持ち上げる。"},
                {1,U"敵を追えば、車のそばが空く。兵を分ければ、前は薄くなる。軍師、どうする。",U"関羽は二つの道へ、駒を一つずつ置く。"},
                {3,U"名乗りを上げる場所より、米が通る場所を先に決める。誰を残すかも、俺が言う。",U"主人公は、追撃の矢印を途中で止めた。"},
                {0,U"それでいい。私の旗は、車を置いて先へは行かない。",U"劉備は自分の駒も、地図へ差し出した。"}});
        else e.lines.insert(e.lines.end(),{
                {1,U"二つの場所を守る。ひと所へ皆を集めれば、片方が空く。",U"関羽が、離れた二点へ石を置いた。"},
                {2,U"だったら片方は俺だ。……ただし、向こうが危なくなったら呼べ。",U"張飛は腕を組んだまま、もう一つの石を見る。"},
                {3,U"走ってくる間も持たせる。そのために、待つ隊と合図を決める。",U"主人公は二つの石の間に、細い線を引く。"},
                {4,U"火が見えたら、こちらは荷を動かします。勝手に消さないでくださいよ。",U"季安が、いつもの縄を肩へ掛ける。"},
                {0,U"小さな火だね。だが、これを頼りに歩く者には、天下より近い。",U"劉備は風を避けるように、灯りの前へ手を置いた。"}});
        if(j.CurrentPledge()==JourneyPledge::Preserve)
            e.lines.push_back({3,U"兵の九割を連れ帰る。護衛も数える。前に俺が言ったことを、今日の配置にする。",U"将たちは、その言葉を覚えている。"});
        else if(j.CurrentPledge()==JourneyPledge::Coordinate)
            e.lines.push_back({3,U"一隊だけでは終わらせない。二隊以上の戦法を、俺の合図でつなぐ。前の約束を、今日の策にする。",U"張飛が、待つ、と小さく頷いた。"});
        e.lines.push_back({0,U"では、決めてくれ。私たちを、どこへ置く。",U"最後の言葉だけは、主人公に残された。"});
    }
}
