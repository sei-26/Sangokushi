#include "JourneyEpisode.hpp"
namespace frontline
{
    JourneyEpisodeLine RoleAftermathVoice(int tone,int actor,int other,bool incoming)
    {
        const char32_t* in[][3]={
            {U"、守りは受け取ったよ。君が出たあとも、あの場所は保てた。",U"、受け渡した後も、守りは保てた。背は預かったぞ。",U"、後ろは俺に任せろ！ あの交代のあとも、ちゃんと守れたぜ！"},
            {U"、戻したよ。……でも、空いた時間まで消えたわけじゃない。",U"、守りは取り戻した。だが、一度途切れたことは覚えておく。",U"、取り戻したぜ！ けど、あの空白までなかったことにはできねえな。"},
            {U"、着けば守れると思った。でも、そこで守りを保てなかった。",U"、場所は替われた。だが、守りを保つには足りなかった。",U"、俺は着いたんだ。なのに守れなかった。何を見落とした？"},
            {U"、場所は替われた。でも、そのあとの守りまでは確かめていないね。",U"、交代の動きは終えた。その先の守りは、まだ確かめておらぬ。",U"、場所は替わったぜ。けど、そのあとまで持ったかは見届けてねえ。"},
            {U"、ここは守れた。でも、もう一方の烽火まで保てたわけじゃない。",U"、この持ち場はつないだ。もう一方の火まで守れたとは言えぬ。",U"、こっちは守ったぜ。けどよ、向こうの火まで続いたわけじゃねえ。"},
            {U"、あの交代の直後は守れた。けれど、今日の結果は別に考えよう。",U"、受け渡した守りは一度はつないだ。今日の結果を、それで隠すな。",U"、交代は噛み合った。けどよ、今日はそれだけで笑えねえだろ。"}};
        const char32_t* out[][3]={
            {U"、後ろを任せられたから出られたよ。軍師、二人で一つの策だったね。",U"が守りを預かったからこそ、私は出られた。軍師、双方の役目をつないだな。",U"の旗が残ってたからな。俺も踏み出せたぜ！ 軍師、出す方も残す方も、ちゃんと呼べよ！"},
            {U"、戻してくれてありがとう。次は、私も受け渡す時を合わせるよ。",U"、待たせた時間があった。次は、守りが渡ったのを見てから出る。",U"、待ってる間は長かったぜ。次は、あの旗を見てから出る。"},
            {U"、君だけに背負わせる話ではないよ。出た私も、あとの守りを一緒に考える。",U"、残る者だけの責ではない。出た私も、その後を策に入れる。",U"だけのせいにはしねえよ。軍師、次は動く前に、俺たちにも考えさせろ。"},
            {U"、合図を出したことと、守ったことは分けて覚えよう。",U"、見届けていない守りを、手柄とは呼べぬな。",U"、次は交代した先まで見ようぜ。着いたところで終わりじゃねえ。"},
            {U"、一つの持ち場がつながっても、両翼がそろったとは言えないね。",U"、一か所の守りで、戦場全部を測るべきではなかった。",U"、そこを守ってくれたのは見てたぜ。向こうの火も、次は見落とさねえ。"},
            {U"、支えは届いたよ。今日の代償まで、それで消えるわけではないけれど。",U"、あの受け渡しと、この戦いの結果は、どちらも残しておこう。",U"、あの交代は忘れねえよ。けど今日の結果も、軍師と一緒に持って帰るぞ。"}};
        const char32_t* address[]={U"兄者",U"雲長",U"翼徳"};
        JourneyEpisodeLine line{actor,std::u32string(address[other])+(incoming ? in[tone][actor]:out[tone][actor]),incoming ? U"後任が、並べられた二つの駒を見る。":U"前任も、自分の駒だけを持ち上げずに答えた。",tone==0 ? 1<<actor:0};
        if(actor==1 && other==0)
        {
            const char32_t* politeIn[]={U"兄者、背は私にお任せください。受け渡したあとも、守りは保てました。",U"兄者、守りは取り戻しました。ですが、一度途切れたことは覚えておきます。",U"兄者、場所は替われました。ですが、守りを保つには足りませんでした。",U"兄者、交代の動きは終えました。その先の守りは、まだ確かめておりません。",U"兄者、この持ち場はつなぎました。もう一方の火まで守れたとは言えません。",U"兄者、受け渡した守りは一度はつなぎました。今日の結果も、別に振り返りましょう。"};
            const char32_t* politeOut[]={U"兄者が守りを預かってくださったからこそ、私は出られました。軍師、双方の役目をつないだな。",U"兄者、待たせた時間がありました。次は、守りが渡ったのを見てから出ます。",U"兄者、残る者だけの責ではありません。出た私も、その後を策に入れます。",U"兄者、見届けていない守りを、手柄とは呼べませんな。",U"兄者、一か所の守りで、戦場全部を測るべきではありませんでした。",U"兄者、あの受け渡しと、この戦いの結果は、どちらも残しておきましょう。"};
            line.text=incoming ? politeIn[tone]:politeOut[tone];
        }
        return line;
    }
}
