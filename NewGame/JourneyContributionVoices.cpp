#include "JourneyEpisode.hpp"
namespace frontline
{
    // Capture, chain speaker, recorded chain partner, or a witness with no chain credit.
    JourneyEpisodeLine ContributionAftermathVoice(int actor,int other,int kind,bool painful)
    {
        const char32_t* positive[][3]={
            {U"旗は替わったよ。けれど、私一人でここへ来たわけじゃない。軍師、皆の働きも覚えていよう。",U"河港の旗は、我らのものだ。軍師、敵を追うだけの策ではなかったな。",U"見たか、軍師！ 港に俺たちの旗だ！ 次は本隊の連中にも、こいつを見せてやろうぜ！"},
            {U"私の一手も、仲間の手につながった。軍師、皆に役目を渡してくれたね。",U"私も連鎖を担った。軍師、一人の武勇では届かぬ手を選んだな。",U"へへっ、俺もちゃんとつないだぜ！ 一人で暴れるだけが能じゃねえだろ？"},
            {U"、私も一手、つないだからね。軍師、皆で次へ行こう。",U"、私も一手を担った。軍師、つないだ者の名も覚えておけ。",U"、俺の一手も忘れんなよ！ 次も声を掛けろ、軍師。合わせてやる！"},
            {U"、旗が替わったね。軍師、今度は本隊と同じ地図を開こう。",U"、旗を替えて終わりではない。軍師、本隊へどうつなぐ。",U"、港が俺たちのものになったんだな！ 本隊にも知らせてやろうぜ！"}};
        const char32_t* costly[][3]={
            {U"港は取れた。けれど、帰ってから話さなければならないことも、残っているね。",U"指揮所は押さえた。軍師、勝利と、その代償を一緒に持ち帰れ。",U"旗は立てたぞ、軍師。……でもよ、今日はそれだけで笑って済ますなよ。"},
            {U"手はつながったよ。でも、その一手だけで、今日の采配を語れないね。",U"連鎖はつないだ。だが軍師、今日の結果は、そこだけでは語れぬ。",U"俺たちの手はつながったぜ。でもよ、それで今日を全部よしにできねえだろ。"},
            {U"、君の働きは覚えているよ。今日の代償も、一緒に話そう。",U"、その働きと、今日の代償の両方を持ち帰ろう。",U"、あの手は忘れねえよ。けど今日の話は、軍師と一緒に最後までしようぜ。"},
            {U"、君の働きは覚えているよ。今日の代償も、一緒に話そう。",U"、その働きと、今日の代償の両方を持ち帰ろう。",U"、あの旗は忘れねえよ。けど今日の話は、軍師と一緒に最後までしようぜ。"}};
        const char32_t* address[]={U"兄者",U"雲長",U"翼徳"};
        std::u32string text=(painful ? costly:positive)[kind][actor];
        if(kind>=2 && other>=0 && other<3)
        {
            text=std::u32string(address[other])+text;
            if(actor==1 && other==0) text=painful ? U"兄者、その働きと、今日の代償の両方を持ち帰りましょう。":
                kind==2 ? U"兄者、私も一手を担いました。軍師、つないだ者の名も覚えておけ。":U"兄者、旗を替えて終わりではありませんな。軍師、本隊へどうつなぐ。";
        }
        return {actor,text,kind==0 ? U"武将は、河港に立つ義勇軍の旗を指さした。":kind==1 || kind==2 ? U"自分の手と仲間の手を、同じ地図の上で振り返る。":U"仲間が、勝利の報せを聞いて応じた。",painful ? 0:1<<actor};
    }
}
