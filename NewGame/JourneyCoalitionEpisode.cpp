#include "JourneyEpisode.hpp"
#include "StrategistJourney.hpp"

namespace frontline
{
    JourneyEpisode BuildCoalitionEpisode(const StrategistJourney& j)
    {
        JourneyEpisode episode;
        if(!j.campaignFlow || j.stage!=JourneyStage::Complete || !j.history[2].won) return episode;

        episode.title=U"第一章　反董卓連合";
        episode.place=U"一八九年 ― 一九〇年　洛陽から関東へ";
        episode.setting=U"史実の政変と挙兵を背景に、義勇軍の軍師を描く。";
        episode.question=U"大軍が集うとき、小さな旗は何のために立つか。";
        episode.lines={
            {-1,U"黄巾の旗を追ってから五年。霊帝が崩じ、大将軍・何進は董卓を都へ呼び寄せた。董卓が着く前に、何進は宦官たちに殺された。",
                U"一八九年・洛陽。宮門が閉じられ、都からの報せは途切れた。"},
            {-1,U"混乱の中で軍を握った董卓は、少帝を退け、陳留王・劉協を帝に立てた。都から逃れた者が、街道を東へ向かった。",
                U"洛陽からの書状が、劉備たちの野営地へ届く。"},
            {2,U"都じゃ、帝の椅子まで兵が運ぶのかよ。兄者、俺たちは何を待ってる？",U"張飛が読みかけの書状を、握ったまま顔を上げる。"},
            {1,U"その兵は、どこの道から来た。逃げた者は、どこへ出る。軍師、都の印より先に、道を見せてくれ。",
                U"関羽が張飛の拳をほどき、しわになった書状を机へ広げる。"},
            {3,j.history[0].rescued ? U"あの車も、道が開くまで誰にも届かなかった。今度は洛陽から来る人に、こちらから道を教えよう。":
                U"道を開いた日に、そこを通る人を見送った。今度は、その人たちが逃げ込める場所まで地図に入れよう。",
                U"軍師は、城の印のあいだに渡し場と村を書き込む。"},
            {-1,U"年が明け、関東の諸侯が董卓を討つために挙兵した。袁紹が盟主に推され、先に陳留で挙兵していた曹操も加わった。",
                U"一九〇年・正月。各地から軍旗が上がり、反董卓連合が結成される。"},
            {2,U"見ろよ、見渡す限り旗だ！ ……で、あの中のどいつが、俺たちに米を渡してくれるんだ？",
                U"張飛が隊列を眺め、途中で声を落とす。"},
            {0,U"それを聞きに行こう。私たちからも、街道の村を戦場にしないよう頼む。誰がその話を聞くか、私が見てくるよ。",
                U"劉備は立ち上がり、畳んでいた自分たちの旗を張飛に預ける。"},
            {3,U"張飛、旗を立ててくれ。関羽は俺と来てくれ。諸侯の返事を待つ間に、村を抜ける道を一緒に見よう。",
                U"軍師は地図を折る。次の軍議へ持っていくのは、村の名が見える地図だ。"}};
        return episode;
    }
}
